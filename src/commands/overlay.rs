//! `dcli-bootc overlay` — RakuOS/rum usr-overlay integration.

use anyhow::{Context, Result};
use colored::*;
use std::collections::HashSet;
use std::path::{Path, PathBuf};

use crate::config::{self, Profile};
use crate::module;
use crate::overlay;
use crate::plan;

/// Header `overlay import` stamps on modules it creates, so a later import
/// may overwrite its own file without `--force`.
const IMPORT_HEADER: &str = "# Generated by 'dcli-bootc overlay import' from the RakuOS usr-overlay.";
const IMPORT_TRAILER: &str =
    "# Packages removed from this list are uninstalled with 'rum remove' on the next build/update.";

/// The overlay module's declared packages — the declarative manifest of what
/// should be installed in the live RakuOS usr-overlay. Not part of the image
/// build (overlay packages stay in the overlay, managed by rum).
fn manifest_packages(project_dir: &Path, profile: &Profile) -> Result<Vec<String>> {
    let Some(module_name) = profile.overlay_module.as_deref() else {
        return Ok(Vec::new());
    };
    let mut pkgs = match config::load_module(project_dir, module_name) {
        Ok(m) => m.packages,
        Err(_) => Vec::new(),
    };
    pkgs.sort();
    pkgs.dedup();
    Ok(pkgs)
}

/// (to_install, to_remove) to make the host overlay match the manifest.
fn diff(installed: &[String], manifest: &[String]) -> (Vec<String>, Vec<String>) {
    let to_install = manifest
        .iter()
        .filter(|p| !installed.contains(p))
        .cloned()
        .collect();
    let to_remove = installed
        .iter()
        .filter(|p| !manifest.contains(p))
        .cloned()
        .collect();
    (to_install, to_remove)
}

/// Package names the base image provides: everything declared by
/// `enabled_modules` (baked into the image), plus whatever the booted base
/// image's own rpmdb reports.
///
/// `rum remove` must never be run against these. `rum` erases with `rpm -e`
/// through the live, overlayfs-merged `/usr`, so unlinking a path that also
/// exists in the base image's lower layer leaves a whiteout in the overlay
/// upperdir — hiding the base copy, permanently. Retaining the overlay copy
/// instead keeps both the overlay entry and the base image intact.
fn base_provided_packages(project_dir: &Path, profile: &Profile) -> HashSet<String> {
    let mut provided = HashSet::new();

    if let Ok(modules) = module::load_enabled_modules(project_dir, &profile.enabled_modules) {
        for rm in &modules {
            provided.extend(rm.module.packages.iter().cloned());
            for entry in &rm.module.local_rpms {
                if let Some(name) = plan::local_rpm_package_name(project_dir, entry) {
                    provided.insert(name);
                }
            }
        }
        // A module that removes a package means the image will not provide it.
        for rm in &modules {
            for removed in &rm.module.remove {
                provided.remove(removed);
            }
        }
    }

    // The booted base image's rpmdb. Best-effort here — if it can't be read,
    // the declared set above is all we have.
    if let Some(base) = booted_base_packages() {
        provided.extend(base);
    }

    provided
}

/// Package names present in the *currently booted* base image's own rpmdb
/// (RakuOS split layout: base packages live in `/usr/share/rpm`, overlay
/// packages in rum's own db). `None` when it can't be read.
fn booted_base_packages() -> Option<HashSet<String>> {
    let out = std::process::Command::new("rpm")
        .args(["-qa", "--dbpath", "/usr/share/rpm", "--queryformat", "%{NAME}\n"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(
        String::from_utf8_lossy(&out.stdout)
            .lines()
            .map(|l| l.trim().to_string())
            .filter(|l| !l.is_empty())
            .collect(),
    )
}

/// Pull base-image-provided packages out of a removal list, returning them
/// separately so callers can report (and keep) them without running `rum`.
fn take_retained(to_remove: &mut Vec<String>, base: &HashSet<String>) -> Vec<String> {
    let mut retained = Vec::new();
    to_remove.retain(|p| {
        if base.contains(p) {
            retained.push(p.clone());
            false
        } else {
            true
        }
    });
    retained
}

/// Split a module's declared packages into (base-provided, remaining): the
/// ones the booted base image already provides, and the ones it doesn't.
fn prune_partition(declared: &[String], base: &HashSet<String>) -> (Vec<String>, Vec<String>) {
    let mut to_prune = Vec::new();
    let mut remaining = Vec::new();
    for p in declared {
        if base.contains(p) {
            to_prune.push(p.clone());
        } else {
            remaining.push(p.clone());
        }
    }
    (to_prune, remaining)
}

fn require_overlay(profile: &Profile) -> Result<&str> {
    let module = profile
        .overlay_module
        .as_deref()
        .context("This project has no 'overlay_module' set in profile.yaml (e.g. 'overlay_module: overlay')")?;
    if !overlay::available() {
        anyhow::bail!(
            "RakuOS rum overlay not found on this host (need /var/lib/rakuos/packages.list and 'rum' in PATH)"
        );
    }
    Ok(module)
}

/// `overlay import`: snapshot the host overlay's packages into the module.
pub fn import(
    project_dir: &Path,
    dry_run: bool,
    force: bool,
    host: Option<&str>,
) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let module_name = require_overlay(&profile)?;

    let installed = overlay::installed_packages()?;
    let path = config::module_path(project_dir, module_name)
        .unwrap_or_else(|| project_dir.join("modules").join(format!("{}.yaml", module_name)));

    println!(
        "{} Importing {} overlay package(s) into {}",
        "▶".cyan(),
        installed.len(),
        path.display()
    );

    if installed.is_empty() {
        println!("  {}", "Overlay has no packages — nothing to write.".dimmed());
        return Ok(());
    }

    if dry_run {
        println!("  Would write packages:");
        for p in &installed {
            println!("    {}", p);
        }
        return Ok(());
    }

    write_module(&path, &installed, force)?;

    println!("{} Wrote {} package(s)", "✓".green(), installed.len());
    if profile.enabled_modules.iter().any(|m| m == module_name) {
        println!(
            "  {} module '{}' is in enabled_modules — its packages will ALSO be baked into the image. Remove it from enabled_modules to keep them overlay-only.",
            "!".yellow(),
            module_name
        );
    }
    let local = overlay::installed_local_rpms();
    if !local.is_empty() {
        println!(
            "  {} Locally-installed overlay RPMs are not imported (no repo provides them) — declare them as local_rpms/remote_rpms: {}",
            "!".yellow(),
            local.join(", ")
        );
    }
    println!(
        "  Next: run 'dcli-bootc overlay sync' (or build/update) to install/remove overlay packages with rum."
    );
    Ok(())
}

/// Write the overlay packages into the module, preserving any other keys
/// already in the file (scripts, repos, ...).
fn write_module(path: &Path, packages: &[String], force: bool) -> Result<()> {
    let mut map: serde_yaml::Mapping = if path.exists() {
        let existing = std::fs::read_to_string(path)
            .with_context(|| format!("Failed to read {}", path.display()))?;

        if !force && !existing.contains(IMPORT_HEADER) {
            let has_packages = serde_yaml::from_str::<serde_yaml::Value>(&existing)
                .ok()
                .and_then(|v| v.get("packages").and_then(|p| p.as_sequence().map(|s| !s.is_empty())))
                .unwrap_or(false);
            if has_packages {
                anyhow::bail!(
                    "{} already declares packages and was not created by dcli-bootc — re-run with --force to overwrite them",
                    path.display()
                );
            }
        }

        match serde_yaml::from_str::<serde_yaml::Value>(&existing)? {
            serde_yaml::Value::Mapping(m) => m,
            _ => anyhow::bail!("{} is not a YAML mapping", path.display()),
        }
    } else {
        serde_yaml::Mapping::new()
    };

    if !map.contains_key("description") {
        map.insert(
            "description".into(),
            "RakuOS usr-overlay packages (imported from rum)".into(),
        );
    }
    map.insert(
        "packages".into(),
        serde_yaml::Value::Sequence(
            packages
                .iter()
                .map(|p| serde_yaml::Value::String(p.clone()))
                .collect(),
        ),
    );

    let yaml = serde_yaml::to_string(&serde_yaml::Value::Mapping(map))?;
    let body = format!("{}\n{}\n{}", IMPORT_HEADER, IMPORT_TRAILER, yaml);
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// Replace a module's `packages:` list, preserving its other keys. Unlike
/// `write_module`, this never refuses on a hand-written module — the caller
/// (`prune`) is explicitly editing an existing manifest — and it re-stamps
/// the `overlay import` header when the file already carried it, so a later
/// `import` can still overwrite its own file without `--force`.
fn rewrite_module_packages(path: &Path, packages: &[String]) -> Result<()> {
    let existing = std::fs::read_to_string(path)
        .with_context(|| format!("Failed to read {}", path.display()))?;
    let mut map: serde_yaml::Mapping = match serde_yaml::from_str::<serde_yaml::Value>(&existing)? {
        serde_yaml::Value::Mapping(m) => m,
        _ => anyhow::bail!("{} is not a YAML mapping", path.display()),
    };

    map.insert(
        "packages".into(),
        serde_yaml::Value::Sequence(
            packages
                .iter()
                .map(|p| serde_yaml::Value::String(p.clone()))
                .collect(),
        ),
    );

    let yaml = serde_yaml::to_string(&serde_yaml::Value::Mapping(map))?;
    let body = if existing.contains(IMPORT_HEADER) {
        format!("{}\n{}\n{}", IMPORT_HEADER, IMPORT_TRAILER, yaml)
    } else {
        yaml
    };
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// `overlay status`: show drift between the host overlay and the manifest.
pub fn status(project_dir: &Path, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let module_name = require_overlay(&profile)?;

    let manifest = manifest_packages(project_dir, &profile)?;
    let installed = overlay::installed_packages()?;
    let (to_install, mut to_remove) = diff(&installed, &manifest);
    let retained = take_retained(
        &mut to_remove,
        &base_provided_packages(project_dir, &profile),
    );

    println!("{} RakuOS overlay (rum)", "▶".cyan());
    println!("  Manifest module: {}", module_name);
    println!("  Overlay packages installed: {}", installed.len());
    println!("  Packages declared in manifest: {}", manifest.len());
    println!();

    let both: Vec<&String> = installed.iter().filter(|p| manifest.contains(p)).collect();
    if !both.is_empty() {
        println!("  {} in overlay and manifest ({}):", "✓".green(), both.len());
        for p in both {
            println!("    {}", p);
        }
    }
    if !to_install.is_empty() {
        println!(
            "  {} declared but not installed ({}):",
            "+".cyan(),
            to_install.len()
        );
        for p in &to_install {
            println!("    {}", p);
        }
    }
    if !to_remove.is_empty() {
        println!(
            "  {} installed but not declared ({}):",
            "-".yellow(),
            to_remove.len()
        );
        for p in &to_remove {
            println!("    {}", p);
        }
    }
    if !retained.is_empty() {
        println!(
            "  {} base image provides, kept in the overlay ({}):",
            "=".cyan(),
            retained.len()
        );
        for p in &retained {
            println!("    {}", p);
        }
    }

    println!();
    if to_install.is_empty() && to_remove.is_empty() {
        if retained.is_empty() {
            println!("{} Overlay matches the manifest.", "✓".green());
        } else {
            println!(
                "{} Overlay matches the manifest ({} base-provided package(s) kept).",
                "✓".green(),
                retained.len()
            );
        }
    } else {
        println!(
            "{} Run 'dcli-bootc overlay sync' (or build/update) to {} and {} with rum.",
            "➜".yellow(),
            format!("install {}", to_install.len()),
            format!("remove {}", to_remove.len())
        );
    }

    // ── Local RPMs ──
    let declared_local = declared_local_rpms(project_dir, &profile);
    let local_names: Vec<String> = declared_local.iter().map(|(_, n)| n.clone()).collect();
    let recorded_local = overlay::installed_local_rpms();
    let local_missing: Vec<&String> = declared_local
        .iter()
        .filter(|(_, n)| !overlay_has_package(n))
        .map(|(_, n)| n)
        .collect();
    let local_stale: Vec<&String> = declared_local
        .iter()
        .filter(|(p, n)| overlay_has_package(n) && staged_needs_repair(p, n))
        .map(|(_, n)| n)
        .collect();
    let local_undeclared = undeclared(&recorded_local, &local_names);
    if !declared_local.is_empty() || !recorded_local.is_empty() {
        println!();
        println!(
            "  Local RPMs ({} declared, {} recorded):",
            declared_local.len(),
            recorded_local.len()
        );
        for n in &local_missing {
            println!("    {} {} (declared, not installed)", "+".cyan(), n);
        }
        for n in &local_stale {
            println!("    {} {} (staged copy missing/blank)", "~".yellow(), n);
        }
        for n in &local_undeclared {
            println!("    {} {} (recorded, not declared)", "-".yellow(), n);
        }
        if local_missing.is_empty() && local_stale.is_empty() && local_undeclared.is_empty() {
            println!(
                "    {} all declared local RPMs installed and staged",
                "✓".green()
            );
        }
    }
    Ok(())
}

/// Reconcile the live host overlay with the manifest module: `rum install`
/// packages the manifest adds, `rum remove` packages it drops. Packages the
/// base image provides are **kept** instead (see `base_provided_packages`).
/// Used by build/update and `overlay sync`. Returns the number of packages
/// actually changed.
pub fn sync(
    project_dir: &Path,
    profile: &Profile,
    force: bool,
    dry_run: bool,
    announce: bool,
) -> Result<usize> {
    if profile.overlay_module.is_none() || !overlay::available() {
        return Ok(0);
    }

    let manifest = manifest_packages(project_dir, profile)?;
    let declared_local = declared_local_rpms(project_dir, profile);
    if manifest.is_empty() && declared_local.is_empty() {
        // Safety: an empty/missing manifest must never wipe the live overlay.
        if announce {
            println!(
                "{} overlay_module '{}' declares no packages — run 'dcli-bootc overlay import' first; nothing to sync.",
                "!".yellow(),
                profile.overlay_module.as_deref().unwrap_or("?")
            );
        }
        return Ok(0);
    }

    let installed = overlay::installed_packages()?;
    // An empty manifest must never imply removals; only a non-empty manifest
    // describes the intended overlay package set.
    let (to_install, mut to_remove) = if manifest.is_empty() {
        (Vec::new(), Vec::new())
    } else {
        diff(&installed, &manifest)
    };
    let retained = take_retained(
        &mut to_remove,
        &base_provided_packages(project_dir, profile),
    );

    // Declared local RPMs that need installing, and installed ones whose staged
    // copy is missing/blank (so a later overlay reset can still reinstall them).
    let local_installed: HashSet<String> = declared_local
        .iter()
        .filter(|(_, name)| overlay_has_package(name))
        .map(|(_, name)| name.clone())
        .collect();
    let local_to_install: Vec<&(PathBuf, String)> = declared_local
        .iter()
        .filter(|(_, name)| !local_installed.contains(name))
        .collect();
    let local_to_stage: Vec<&(PathBuf, String)> = declared_local
        .iter()
        .filter(|(path, name)| local_installed.contains(name) && staged_needs_repair(path, name))
        .collect();

    if to_install.is_empty()
        && to_remove.is_empty()
        && local_to_install.is_empty()
        && local_to_stage.is_empty()
    {
        if announce {
            if retained.is_empty() {
                println!("{} Overlay matches the manifest.", "✓".green());
            } else {
                println!(
                    "{} Overlay matches the manifest; {} base-provided package(s) kept in the overlay:",
                    "✓".green(),
                    retained.len()
                );
                for p in &retained {
                    println!("    {} {}", "=".cyan(), p);
                }
                println!(
                    "  {} Removing these with rum would hide the base image's copies — leaving them.",
                    "!".yellow()
                );
            }
        }
        return Ok(0);
    }

    println!();
    println!(
        "{} RakuOS overlay sync with '{}':",
        "▶".cyan(),
        profile.overlay_module.as_deref().unwrap_or("?")
    );
    for p in &to_install {
        println!("    {} install {}", "+".green(), p);
    }
    for p in &to_remove {
        println!("    {} remove  {}", "-".yellow(), p);
    }
    for p in &retained {
        println!(
            "    {} keep    {} (base image provides it)",
            "=".cyan(),
            p
        );
    }
    for (path, name) in &local_to_install {
        println!(
            "    {} install {} (local RPM: {})",
            "+".green(),
            name,
            path.display()
        );
    }
    for (_, name) in &local_to_stage {
        println!(
            "    {} restage {} (staged copy missing/blank)",
            "~".cyan(),
            name
        );
    }

    if dry_run {
        println!("  (dry run — nothing changed)");
        return Ok(0);
    }

    if !force && !crate::bootc::confirm("Apply these changes to the live usr-overlay with rum?") {
        println!("  Skipped — run 'dcli-bootc overlay sync' when ready.");
        return Ok(0);
    }

    overlay::install_packages(&to_install, false)?;
    overlay::remove_packages(&to_remove, false)?;
    for (path, name) in &local_to_stage {
        overlay::stage_local_rpm(path, name)?;
    }
    for (path, _) in &local_to_install {
        overlay::install_local_rpm(path, false)?;
    }

    let mut extras = Vec::new();
    if !retained.is_empty() {
        extras.push(format!("{} base-provided kept", retained.len()));
    }
    if !local_to_install.is_empty() {
        extras.push(format!("{} local RPM(s) installed", local_to_install.len()));
    }
    if !local_to_stage.is_empty() {
        extras.push(format!("{} local RPM(s) restaged", local_to_stage.len()));
    }
    let suffix = if extras.is_empty() {
        String::new()
    } else {
        format!(", {}", extras.join(", "))
    };
    println!(
        "{} Overlay synced ({} installed, {} removed{})",
        "✓".green(),
        to_install.len(),
        to_remove.len(),
        suffix
    );
    Ok(to_install.len() + to_remove.len() + local_to_install.len() + local_to_stage.len())
}

/// `dcli-bootc overlay sync` — the build/update hook, on demand.
pub fn sync_command(project_dir: &Path, force: bool, dry_run: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    require_overlay(&profile)?;
    sync(project_dir, &profile, force, dry_run, true)?;
    Ok(())
}

/// `dcli-bootc overlay prune` — drop from the overlay module every package
/// the currently booted base image already provides.
///
/// Unlike `base_provided_packages`, this deliberately consults *only* the
/// booted base image's rpmdb (`/usr/share/rpm`) and never the
/// `enabled_modules` declarations: a package is pruned only once it is
/// actually installed and running, never merely declared for a build that
/// hasn't booted yet.
pub fn prune(project_dir: &Path, dry_run: bool, force: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let module_name = require_overlay(&profile)?;

    let path = config::module_path(project_dir, module_name).unwrap_or_else(|| {
        project_dir
            .join("modules")
            .join(format!("{}.yaml", module_name))
    });
    let module = config::load_module(project_dir, module_name)?;

    let mut declared = module.packages;
    declared.sort();
    declared.dedup();

    let base = booted_base_packages().context(
        "Could not read the booted base image's rpmdb at /usr/share/rpm — refusing to prune without it",
    )?;
    let (to_prune, remaining) = prune_partition(&declared, &base);

    if to_prune.is_empty() {
        println!(
            "{} Nothing to prune — no package in '{}' is provided by the booted base image.",
            "✓".green(),
            module_name
        );
        return Ok(());
    }

    println!(
        "{} Pruning {} base-provided package(s) from {}",
        "▶".cyan(),
        to_prune.len(),
        path.display()
    );
    for p in &to_prune {
        println!("    {} {}", "-".yellow(), p);
    }
    println!("    {} left in the module", remaining.len());

    if dry_run {
        println!("  (dry run — nothing written)");
        return Ok(());
    }

    if !force
        && !crate::bootc::confirm("Remove these base-provided packages from the overlay module?")
    {
        println!("  Skipped.");
        return Ok(());
    }

    rewrite_module_packages(&path, &remaining)?;

    println!(
        "{} Pruned {} package(s) from '{}'; {} left",
        "✓".green(),
        to_prune.len(),
        module_name,
        remaining.len()
    );
    println!(
        "  {} Live overlay copies are left as-is (removing them with rum would hide the base image's copies). Reclaim them with 'rakuos reset-overlay --soft'.",
        "!".yellow()
    );
    Ok(())
}

/// The overlay module's declared local RPM filenames.
fn manifest_local_rpms(project_dir: &Path, profile: &Profile) -> Vec<String> {
    let Some(module_name) = profile.overlay_module.as_deref() else {
        return Vec::new();
    };
    config::load_module(project_dir, module_name)
        .map(|m| m.local_rpms)
        .unwrap_or_default()
}

/// Declared overlay local RPMs resolved to (project path, package name).
fn declared_local_rpms(project_dir: &Path, profile: &Profile) -> Vec<(PathBuf, String)> {
    manifest_local_rpms(project_dir, profile)
        .into_iter()
        .filter_map(|entry| {
            let name = plan::local_rpm_package_name(project_dir, &entry)?;
            Some((project_dir.join("rpms").join(entry), name))
        })
        .collect()
}

/// True when rum's staged copy of a local RPM is missing, blank, or a different
/// size than the project's file (e.g. after a soft reset blanked it).
fn staged_needs_repair(src: &Path, name: &str) -> bool {
    let staged = overlay::staged_local_rpm(name);
    match (std::fs::metadata(src), std::fs::metadata(&staged)) {
        (Ok(s), Ok(d)) => d.len() == 0 || d.len() != s.len(),
        (_, Err(_)) => true,
        (Err(_), _) => false,
    }
}

/// True when `name` is actually installed in the live usr-overlay (rum's own
/// rpmdb). `packages-rpm.list` can outlive the install — e.g. a soft reset that
/// failed to reinstall from a blanked staged copy leaves the name recorded but
/// the package absent.
fn overlay_has_package(name: &str) -> bool {
    std::process::Command::new("rpm")
        .args(["-q", "--dbpath", "/var/lib/rakuos/rum-rpmdb", name])
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Entries present in `have` but absent from `want`.
fn undeclared(have: &[String], want: &[String]) -> Vec<String> {
    have.iter()
        .filter(|p| !want.contains(p))
        .cloned()
        .collect()
}

/// `dcli-bootc overlay clean` — rewrite the live overlay's package lists so
/// they match the overlay module exactly, then offer to schedule the soft
/// reset that rebuilds the overlay from them.
///
/// `sync` reconciles the overlay with `rum`, but `rum` must never remove a
/// package the base image provides (it would whiteout the base copy), and
/// `rakuos reset-overlay --soft` preserves `packages.list` — so entries the
/// base now provides (or that were dropped from the module) otherwise linger
/// in the live overlay forever. This is the command that clears them.
pub fn clean(
    project_dir: &Path,
    dry_run: bool,
    force: bool,
    no_reset: bool,
    host: Option<&str>,
) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let module_name = require_overlay(&profile)?.to_string();

    let mut declared = manifest_packages(project_dir, &profile)?;
    if declared.is_empty() {
        anyhow::bail!(
            "overlay_module '{}' declares no packages — refusing to clean the live overlay. Run 'dcli-bootc overlay import' first.",
            module_name
        );
    }
    declared.sort();
    declared.dedup();

    let declared_local_entries = manifest_local_rpms(project_dir, &profile);
    let mut declared_local: Vec<String> = declared_local_entries
        .iter()
        .filter_map(|e| plan::local_rpm_package_name(project_dir, e))
        .collect();
    declared_local.sort();
    declared_local.dedup();

    let installed = overlay::installed_packages()?;
    let installed_local = overlay::installed_local_rpms();
    let base = base_provided_packages(project_dir, &profile);

    let repo_drops = undeclared(&installed, &declared);
    let local_drops = undeclared(&installed_local, &declared_local);

    println!("{} RakuOS overlay clean", "▶".cyan());
    println!("  Manifest module: {}", module_name);
    println!("  packages.list:     {} -> {}", installed.len(), declared.len());
    println!(
        "  packages-rpm.list: {} -> {}",
        installed_local.len(),
        declared_local.len()
    );
    println!();

    if repo_drops.is_empty() && local_drops.is_empty() {
        println!(
            "{} Live lists already match the manifest — nothing to drop.",
            "✓".green()
        );
    }
    if !repo_drops.is_empty() {
        println!("  {} package(s) to drop from packages.list:", "-".yellow());
        for p in &repo_drops {
            if base.contains(p) {
                println!(
                    "    {} {} {}",
                    "=".cyan(),
                    p,
                    "(base image provides it)".dimmed()
                );
            } else {
                println!("    {} {}", "-".yellow(), p);
            }
        }
    }
    if !local_drops.is_empty() {
        println!(
            "  {} local RPM(s) to drop from packages-rpm.list:",
            "-".yellow()
        );
        for p in &local_drops {
            println!("    {} {}", "-".yellow(), p);
        }
    }
    if !repo_drops.is_empty() {
        println!();
        println!(
            "  {} Entries not marked \"(base image provides it)\" will be gone after the reset.",
            "!".yellow()
        );
    }

    // Declared local RPMs the reset would not be able to reinstall.
    for entry in &declared_local_entries {
        if plan::local_rpm_package_name(project_dir, entry).is_none() {
            println!(
                "  {} Could not read local RPM '{}' from the project's rpms/ directory.",
                "!".yellow(),
                entry
            );
        }
    }
    let local_dir = Path::new("/var/lib/rakuos/local-rpms");
    for name in &declared_local {
        let stored = local_dir.join(format!("{}.rpm", name));
        if !stored.exists() {
            println!(
                "  {} No stored copy for local RPM '{}' at {} — the reset cannot reinstall it.",
                "!".yellow(),
                name,
                stored.display()
            );
        }
    }

    if dry_run {
        println!("  (dry run — nothing written)");
        return Ok(());
    }

    let changed = !repo_drops.is_empty() || !local_drops.is_empty();
    if changed {
        if !force
            && !crate::bootc::confirm("Rewrite the live overlay lists and prepare a reset?")
        {
            println!("  Skipped.");
            return Ok(());
        }
        overlay::write_package_lists(&declared, &declared_local)?;
        println!(
            "{} Wrote packages.list ({} entries) and packages-rpm.list ({} entries); originals saved as .bak",
            "✓".green(),
            declared.len(),
            declared_local.len()
        );
    } else {
        println!("{} Live lists already match the manifest.", "✓".green());
    }

    if no_reset {
        println!();
        println!("  Next: run 'sudo rakuos reset-overlay --soft' and reboot to rebuild the overlay.");
        return Ok(());
    }

    if force || crate::bootc::confirm("Run 'sudo rakuos reset-overlay --soft' now?") {
        overlay::schedule_soft_reset()?;
        println!(
            "{} Soft reset scheduled — reboot to rebuild the overlay.",
            "✓".green()
        );
        println!("  Run 'sudo reboot' when ready.");
    } else {
        println!();
        println!("  Skipped. Run 'sudo rakuos reset-overlay --soft' and reboot when ready.");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn diff_is_bidirectional() {
        let installed = ["a", "b", "c"].map(String::from).to_vec();
        let manifest = ["b", "d"].map(String::from).to_vec();
        let (to_install, to_remove) = diff(&installed, &manifest);
        assert_eq!(to_install, ["d"]);
        assert_eq!(to_remove, ["a", "c"]);
    }

    #[test]
    fn prune_partition_separates_base_provided() {
        let declared = ["a", "b", "c"].map(String::from).to_vec();
        let base: HashSet<String> = ["b", "c", "d"].map(String::from).into_iter().collect();
        let (to_prune, remaining) = prune_partition(&declared, &base);
        assert_eq!(to_prune, ["b", "c"]);
        assert_eq!(remaining, ["a"]);
    }

    #[test]
    fn take_retained_pulls_base_provided_out_of_removals() {
        let base: HashSet<String> = ["foo".to_string()].into_iter().collect();
        let mut to_remove = vec!["foo".to_string(), "bar".to_string()];
        let retained = take_retained(&mut to_remove, &base);
        assert_eq!(to_remove, ["bar"]);
        assert_eq!(retained, ["foo"]);
    }

    #[test]
    fn write_module_merges_and_preserves_other_keys() {
        let dir = std::env::temp_dir().join(format!("dcli-overlay-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("overlay.yaml");
        std::fs::write(&path, "description: keep me\nscripts:\n  post: echo hi\n").unwrap();

        write_module(&path, &["steam".to_string()], false).unwrap();

        let out = std::fs::read_to_string(&path).unwrap();
        assert!(out.contains("keep me"), "{out}");
        assert!(out.contains("echo hi"), "{out}");
        assert!(out.contains("- steam"), "{out}");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn undeclared_finds_entries_missing_from_want() {
        let have = ["a", "b", "c"].map(String::from).to_vec();
        let want = ["b", "d"].map(String::from).to_vec();
        assert_eq!(undeclared(&have, &want), ["a", "c"]);
        assert_eq!(undeclared(&want, &have), ["d"]);
    }
}
