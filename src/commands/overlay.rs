//! `dcli-bootc overlay` — persistent usr-overlay integration.
//!
//! Works against either supported backend (RakuOS `rum` or kineticos
//! `kinpkg`); see `crate::overlay`. The reconciliation logic here (manifest
//! loading, diffing, base-package protection, local-RPM staging) is shared.

use anyhow::{Context, Result};
use colored::*;
use std::collections::HashSet;
use std::path::{Path, PathBuf};

use crate::config::{self, Profile};
use crate::module;
use crate::overlay::{self, OverlayBackend};
use crate::plan;

/// Stable marker `overlay import` stamps on modules it creates, so a later
/// import may overwrite its own file without `--force`. Backend-specific
/// detail (the overlay it came from) follows on the same line.
const IMPORT_MARKER: &str = "# Generated by 'dcli-bootc overlay import'";

fn import_header(backend: &dyn OverlayBackend) -> String {
    format!("{} from the {}.", IMPORT_MARKER, backend.label())
}

fn import_trailer(backend: &dyn OverlayBackend) -> String {
    format!(
        "# Packages removed from this list are uninstalled with '{} remove' on the next build/update.",
        backend.tool()
    )
}

fn import_description(backend: &dyn OverlayBackend) -> String {
    format!("usr-overlay packages (imported from {})", backend.tool())
}

/// The overlay module's declared packages — the declarative manifest of what
/// should be installed in the live usr-overlay. Not part of the image build
/// (overlay packages stay in the overlay, managed by the backend).
fn manifest_packages(project_dir: &Path, profile: &Profile) -> Result<Vec<String>> {
    let Some(module_name) = profile.overlay_module.as_deref() else {
        return Ok(Vec::new());
    };
    let mut pkgs = match config::load_module(project_dir, module_name) {
        Ok(m) => m.packages,
        Err(_) => Vec::new(),
    };
    pkgs.sort();
    pkgs.dedup();
    Ok(pkgs)
}

/// (to_install, to_remove) to make the host overlay match the manifest.
fn diff(installed: &[String], manifest: &[String]) -> (Vec<String>, Vec<String>) {
    let to_install = manifest
        .iter()
        .filter(|p| !installed.contains(p))
        .cloned()
        .collect();
    let to_remove = installed
        .iter()
        .filter(|p| !manifest.contains(p))
        .cloned()
        .collect();
    (to_install, to_remove)
}

/// Package names the base image provides: everything declared by
/// `enabled_modules` (baked into the image), plus whatever the backend can
/// report about the booted base image's own packages.
///
/// The backend's remover must never be run against these. It erases through
/// the live, overlayfs-merged `/usr`, so unlinking a path that also exists in
/// the base image's lower layer leaves a whiteout in the overlay upperdir —
/// hiding the base copy, permanently. Retaining the overlay copy instead keeps
/// both the overlay entry and the base image intact.
fn base_provided_packages(
    project_dir: &Path,
    profile: &Profile,
    backend: &dyn OverlayBackend,
) -> HashSet<String> {
    let mut provided = HashSet::new();

    if let Ok(modules) = module::load_enabled_modules(project_dir, &profile.enabled_modules) {
        for rm in &modules {
            provided.extend(rm.module.packages.iter().cloned());
            for entry in &rm.module.local_rpms {
                if let Some(name) = plan::local_rpm_package_name(project_dir, entry) {
                    provided.insert(name);
                }
            }
        }
    }

    // A module that removes a package means the image will not provide it.
    for removed in removed_packages(project_dir, profile) {
        provided.remove(&removed);
    }

    // The booted base image's packages, as far as the backend can determine.
    if let Some(base) = backend.base_packages() {
        provided.extend(base);
    }

    provided
}

/// Package names the enabled modules explicitly remove from the image. These
/// must never be re-introduced through the overlay manifest: a stale rpmdb
/// entry in the live overlay would otherwise be snapshotted by `import` and
/// then kept installed by `sync`.
fn removed_packages(project_dir: &Path, profile: &Profile) -> HashSet<String> {
    let mut removed = HashSet::new();
    if let Ok(modules) = module::load_enabled_modules(project_dir, &profile.enabled_modules) {
        for rm in &modules {
            removed.extend(rm.module.remove.iter().cloned());
        }
    }
    removed
}

/// Pull base-image-provided packages out of a removal list, returning them
/// separately so callers can report (and keep) them without invoking the
/// backend's remover.
fn take_retained(to_remove: &mut Vec<String>, base: &HashSet<String>) -> Vec<String> {
    let mut retained = Vec::new();
    to_remove.retain(|p| {
        if base.contains(p) {
            retained.push(p.clone());
            false
        } else {
            true
        }
    });
    retained
}

/// Split a module's declared packages into (base-provided, remaining): the
/// ones the booted base image already provides, and the ones it doesn't.
fn prune_partition(declared: &[String], base: &HashSet<String>) -> (Vec<String>, Vec<String>) {
    let mut to_prune = Vec::new();
    let mut remaining = Vec::new();
    for p in declared {
        if base.contains(p) {
            to_prune.push(p.clone());
        } else {
            remaining.push(p.clone());
        }
    }
    (to_prune, remaining)
}

/// Resolve the overlay module and a usable backend, or explain what is missing.
fn require_overlay(profile: &Profile) -> Result<(&str, Box<dyn OverlayBackend>)> {
    let module = profile
        .overlay_module
        .as_deref()
        .context("This project has no 'overlay_module' set in profile.yaml (e.g. 'overlay_module: overlay')")?;
    let backend = overlay::select(profile.overlay_backend)
        .with_context(|| overlay::unavailable_message(profile.overlay_backend))?;
    Ok((module, backend))
}

/// `overlay import`: snapshot the host overlay's packages into the module.
pub fn import(
    project_dir: &Path,
    dry_run: bool,
    force: bool,
    quiet: bool,
    host: Option<&str>,
) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let (module_name, backend) = require_overlay(&profile)?;
    let backend: &dyn OverlayBackend = &*backend;

    let mut installed = backend.installed_packages()?;
    let removed = removed_packages(project_dir, &profile);
    let skipped: Vec<String> = installed
        .iter()
        .filter(|p| removed.contains(*p))
        .cloned()
        .collect();
    installed.retain(|p| !removed.contains(p));

    let path = config::module_path(project_dir, module_name)
        .unwrap_or_else(|| project_dir.join("modules").join(format!("{}.yaml", module_name)));

    if !quiet {
        println!(
            "{} Importing {} overlay package(s) into {}",
            "▶".cyan(),
            installed.len(),
            path.display()
        );

        if !skipped.is_empty() {
            println!(
                "  {} Skipping {} package(s) the image removes: {}",
                "!".yellow(),
                skipped.len(),
                skipped.join(", ")
            );
        }
    }

    if installed.is_empty() {
        if !quiet {
            println!("  {}", "Overlay has no packages — nothing to write.".dimmed());
        }
        return Ok(());
    }

    if dry_run {
        println!("  Would write packages:");
        for p in &installed {
            println!("    {}", p);
        }
        return Ok(());
    }

    // Idempotence: skip rewriting when the module already lists exactly these
    // packages, so an automatic snapshot never reformats the file (or creates
    // noisy diffs) when nothing changed.
    if manifest_packages(project_dir, &profile).unwrap_or_default() == installed {
        if !quiet {
            println!("{} Overlay module already matches the live overlay.", "✓".green());
        }
        return Ok(());
    }

    write_module(&path, &installed, force, backend)?;

    if !quiet {
        println!("{} Wrote {} package(s)", "✓".green(), installed.len());
        if profile.enabled_modules.iter().any(|m| m == module_name) {
            println!(
                "  {} module '{}' is in enabled_modules — its packages will ALSO be baked into the image. Remove it from enabled_modules to keep them overlay-only.",
                "!".yellow(),
                module_name
            );
        }
        let local = backend.installed_local_rpms();
        if !local.is_empty() {
            println!(
                "  {} Locally-installed overlay RPMs are not imported (no repo provides them) — declare them as local_rpms/remote_rpms: {}",
                "!".yellow(),
                local.join(", ")
            );
        }
        println!(
            "  Next: run 'dcli-bootc overlay sync' (or build/update) to install/remove overlay packages with {}.",
            backend.tool()
        );
    }
    Ok(())
}

/// Live overlay packages that the manifest does not declare and that the base
/// image does not provide — the set an additive sync keeps in place. Used by
/// build/update (`--no-import`) to tell the user what is not recorded yet.
pub fn undeclared_live_packages(project_dir: &Path, profile: &Profile) -> Result<Vec<String>> {
    if profile.overlay_module.is_none() {
        return Ok(Vec::new());
    }
    let Some(backend) = overlay::select(profile.overlay_backend) else {
        return Ok(Vec::new());
    };
    let backend: &dyn OverlayBackend = &*backend;

    let manifest = manifest_packages(project_dir, profile)?;
    if manifest.is_empty() {
        // `sync` treats an empty manifest as "leave the live overlay alone".
        return Ok(Vec::new());
    }
    let installed = backend.installed_packages()?;
    let (_, mut to_remove) = diff(&installed, &manifest);
    let _ = take_retained(
        &mut to_remove,
        &base_provided_packages(project_dir, profile, backend),
    );
    Ok(to_remove)
}

/// Write the overlay packages into the module, preserving any other keys
/// already in the file (scripts, repos, ...).
fn write_module(
    path: &Path,
    packages: &[String],
    force: bool,
    backend: &dyn OverlayBackend,
) -> Result<()> {
    let mut map: serde_yaml::Mapping = if path.exists() {
        let existing = std::fs::read_to_string(path)
            .with_context(|| format!("Failed to read {}", path.display()))?;

        if !force && !existing.contains(IMPORT_MARKER) {
            let has_packages = serde_yaml::from_str::<serde_yaml::Value>(&existing)
                .ok()
                .and_then(|v| v.get("packages").and_then(|p| p.as_sequence().map(|s| !s.is_empty())))
                .unwrap_or(false);
            if has_packages {
                anyhow::bail!(
                    "{} already declares packages and was not created by dcli-bootc — re-run with --force to overwrite them",
                    path.display()
                );
            }
        }

        match serde_yaml::from_str::<serde_yaml::Value>(&existing)? {
            serde_yaml::Value::Mapping(m) => m,
            _ => anyhow::bail!("{} is not a YAML mapping", path.display()),
        }
    } else {
        serde_yaml::Mapping::new()
    };

    if !map.contains_key("description") {
        map.insert(
            "description".into(),
            import_description(backend).into(),
        );
    }
    map.insert(
        "packages".into(),
        serde_yaml::Value::Sequence(
            packages
                .iter()
                .map(|p| serde_yaml::Value::String(p.clone()))
                .collect(),
        ),
    );

    let yaml = serde_yaml::to_string(&serde_yaml::Value::Mapping(map))?;
    let body = format!(
        "{}\n{}\n{}",
        import_header(backend),
        import_trailer(backend),
        yaml
    );
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// Replace a module's `packages:` list, preserving its other keys. Unlike
/// `write_module`, this never refuses on a hand-written module — the caller
/// (`prune`) is explicitly editing an existing manifest — and it re-stamps
/// the `overlay import` header when the file already carried it, so a later
/// `import` can still overwrite its own file without `--force`.
fn rewrite_module_packages(
    path: &Path,
    packages: &[String],
    backend: &dyn OverlayBackend,
) -> Result<()> {
    let existing = std::fs::read_to_string(path)
        .with_context(|| format!("Failed to read {}", path.display()))?;
    let mut map: serde_yaml::Mapping = match serde_yaml::from_str::<serde_yaml::Value>(&existing)? {
        serde_yaml::Value::Mapping(m) => m,
        _ => anyhow::bail!("{} is not a YAML mapping", path.display()),
    };

    map.insert(
        "packages".into(),
        serde_yaml::Value::Sequence(
            packages
                .iter()
                .map(|p| serde_yaml::Value::String(p.clone()))
                .collect(),
        ),
    );

    let yaml = serde_yaml::to_string(&serde_yaml::Value::Mapping(map))?;
    let body = if existing.contains(IMPORT_MARKER) {
        format!(
            "{}\n{}\n{}",
            import_header(backend),
            import_trailer(backend),
            yaml
        )
    } else {
        yaml
    };
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// `overlay status`: show drift between the host overlay and the manifest.
pub fn status(project_dir: &Path, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let (module_name, backend) = require_overlay(&profile)?;
    let backend: &dyn OverlayBackend = &*backend;

    let manifest = manifest_packages(project_dir, &profile)?;
    let installed = backend.installed_packages()?;
    let (to_install, mut to_remove) = diff(&installed, &manifest);
    let retained = take_retained(
        &mut to_remove,
        &base_provided_packages(project_dir, &profile, backend),
    );

    println!("{} {}", "▶".cyan(), backend.label());
    println!("  Manifest module: {}", module_name);
    println!("  Overlay packages installed: {}", installed.len());
    println!("  Packages declared in manifest: {}", manifest.len());
    println!();

    let both: Vec<&String> = installed.iter().filter(|p| manifest.contains(p)).collect();
    if !both.is_empty() {
        println!("  {} in overlay and manifest ({}):", "✓".green(), both.len());
        for p in both {
            println!("    {}", p);
        }
    }
    if !to_install.is_empty() {
        println!(
            "  {} declared but not installed ({}):",
            "+".cyan(),
            to_install.len()
        );
        for p in &to_install {
            println!("    {}", p);
        }
    }
    if !to_remove.is_empty() {
        println!(
            "  {} installed but not declared ({}):",
            "-".yellow(),
            to_remove.len()
        );
        for p in &to_remove {
            println!("    {}", p);
        }
    }
    if !retained.is_empty() {
        println!(
            "  {} base image provides, kept in the overlay ({}):",
            "=".cyan(),
            retained.len()
        );
        for p in &retained {
            println!("    {}", p);
        }
    }

    println!();
    if to_install.is_empty() && to_remove.is_empty() {
        if retained.is_empty() {
            println!("{} Overlay matches the manifest.", "✓".green());
        } else {
            println!(
                "{} Overlay matches the manifest ({} base-provided package(s) kept).",
                "✓".green(),
                retained.len()
            );
        }
    } else {
        println!(
            "{} Run 'dcli-bootc overlay sync' (or build/update) to {} and {} with {}.",
            "➜".yellow(),
            format!("install {}", to_install.len()),
            format!("remove {}", to_remove.len()),
            backend.tool()
        );
    }

    // ── Local RPMs ──
    let declared_local = if backend.supports_local_rpms() {
        declared_local_rpms(project_dir, &profile)
    } else {
        Vec::new()
    };
    let local_names: Vec<String> = declared_local.iter().map(|(_, n)| n.clone()).collect();
    let recorded_local = backend.installed_local_rpms();
    let local_missing: Vec<&String> = declared_local
        .iter()
        .filter(|(_, n)| !backend.has_package(n))
        .map(|(_, n)| n)
        .collect();
    let local_stale: Vec<&String> = declared_local
        .iter()
        .filter(|(p, n)| backend.has_package(n) && staged_needs_repair(backend, p, n))
        .map(|(_, n)| n)
        .collect();
    let local_undeclared = undeclared(&recorded_local, &local_names);
    if !declared_local.is_empty() || !recorded_local.is_empty() {
        println!();
        println!(
            "  Local RPMs ({} declared, {} recorded):",
            declared_local.len(),
            recorded_local.len()
        );
        for n in &local_missing {
            println!("    {} {} (declared, not installed)", "+".cyan(), n);
        }
        for n in &local_stale {
            println!("    {} {} (staged copy missing/blank)", "~".yellow(), n);
        }
        for n in &local_undeclared {
            println!("    {} {} (recorded, not declared)", "-".yellow(), n);
        }
        if local_missing.is_empty() && local_stale.is_empty() && local_undeclared.is_empty() {
            println!(
                "    {} all declared local RPMs installed and staged",
                "✓".green()
            );
        }
    }
    Ok(())
}

/// Reconcile the live host overlay with the manifest module: install packages
/// the manifest adds, remove packages it drops. Packages the base image
/// provides are **kept** instead (see `base_provided_packages`). Used by
/// build/update and `overlay sync`. Returns the number of packages actually
/// changed.
///
/// `remove_extra` controls whether live packages the manifest does not declare
/// are removed. build/update pass `false`, making the manifest a floor: new
/// packages are installed, but anything the user installed live is left alone
/// (so a plain `dnf`/`kinpkg install` is never silently undone). Only an
/// explicit `overlay sync` passes `true` and treats the manifest as
/// authoritative.
pub fn sync(
    project_dir: &Path,
    profile: &Profile,
    force: bool,
    dry_run: bool,
    announce: bool,
    remove_extra: bool,
) -> Result<usize> {
    if profile.overlay_module.is_none() {
        return Ok(0);
    }
    let Some(backend) = overlay::select(profile.overlay_backend) else {
        return Ok(0);
    };
    let backend: &dyn OverlayBackend = &*backend;

    let manifest = manifest_packages(project_dir, profile)?;
    let declared_local = if backend.supports_local_rpms() {
        declared_local_rpms(project_dir, profile)
    } else {
        if !manifest_local_rpms(project_dir, profile).is_empty() {
            eprintln!(
                "{} overlay backend '{}' does not manage local RPMs — ignoring declared local_rpms.",
                "!".yellow(),
                backend.id()
            );
        }
        Vec::new()
    };
    if manifest.is_empty() && declared_local.is_empty() {
        // Safety: an empty/missing manifest must never wipe the live overlay.
        if announce {
            println!(
                "{} overlay_module '{}' declares no packages — run 'dcli-bootc overlay import' first; nothing to sync.",
                "!".yellow(),
                profile.overlay_module.as_deref().unwrap_or("?")
            );
        }
        return Ok(0);
    }

    let installed = backend.installed_packages()?;
    // An empty manifest must never imply removals; only a non-empty manifest
    // describes the intended overlay package set.
    let (to_install, undeclared) = if manifest.is_empty() {
        (Vec::new(), Vec::new())
    } else {
        diff(&installed, &manifest)
    };
    // Additive callers (build/update) keep undeclared live packages; only an
    // authoritative `overlay sync` removes them.
    let mut to_remove: Vec<String> = if remove_extra {
        undeclared.clone()
    } else {
        Vec::new()
    };
    let retained = take_retained(
        &mut to_remove,
        &base_provided_packages(project_dir, profile, backend),
    );
    // Undeclared live packages deliberately left in place by an additive sync.
    let kept: Vec<&String> = if remove_extra {
        Vec::new()
    } else {
        undeclared.iter().collect()
    };

    // Declared local RPMs that need installing, and installed ones whose staged
    // copy is missing/blank (so a later overlay reset can still reinstall them).
    let local_installed: HashSet<String> = declared_local
        .iter()
        .filter(|(_, name)| backend.has_package(name))
        .map(|(_, name)| name.clone())
        .collect();
    let local_to_install: Vec<&(PathBuf, String)> = declared_local
        .iter()
        .filter(|(_, name)| !local_installed.contains(name))
        .collect();
    let local_to_stage: Vec<&(PathBuf, String)> = declared_local
        .iter()
        .filter(|(path, name)| local_installed.contains(name) && staged_needs_repair(backend, path, name))
        .collect();

    if to_install.is_empty()
        && to_remove.is_empty()
        && local_to_install.is_empty()
        && local_to_stage.is_empty()
    {
        if announce {
            if !kept.is_empty() {
                println!(
                    "{} Overlay matches the manifest; {} live package(s) not declared were kept:",
                    "✓".green(),
                    kept.len()
                );
                for p in &kept {
                    println!("    {} {}", "=".cyan(), p);
                }
            } else if retained.is_empty() {
                println!("{} Overlay matches the manifest.", "✓".green());
            } else {
                println!(
                    "{} Overlay matches the manifest; {} base-provided package(s) kept in the overlay:",
                    "✓".green(),
                    retained.len()
                );
                for p in &retained {
                    println!("    {} {}", "=".cyan(), p);
                }
                println!(
                    "  {} Removing these with {} would hide the base image's copies — leaving them.",
                    "!".yellow(),
                    backend.tool()
                );
            }
        }
        return Ok(0);
    }

    println!();
    println!(
        "{} {} sync with '{}':",
        "▶".cyan(),
        backend.label(),
        profile.overlay_module.as_deref().unwrap_or("?")
    );
    for p in &to_install {
        println!("    {} install {}", "+".green(), p);
    }
    for p in &to_remove {
        println!("    {} remove  {}", "-".yellow(), p);
    }
    for p in &retained {
        println!(
            "    {} keep    {} (base image provides it)",
            "=".cyan(),
            p
        );
    }
    if !kept.is_empty() {
        if announce {
            for p in &kept {
                println!("    {} keep    {} (not declared)", "=".cyan(), p);
            }
        } else {
            println!(
                "    {} keep    {} live package(s) not declared (additive sync)",
                "=".cyan(),
                kept.len()
            );
        }
    }
    for (path, name) in &local_to_install {
        println!(
            "    {} install {} (local RPM: {})",
            "+".green(),
            name,
            path.display()
        );
    }
    for (_, name) in &local_to_stage {
        println!(
            "    {} restage {} (staged copy missing/blank)",
            "~".cyan(),
            name
        );
    }

    if dry_run {
        println!("  (dry run — nothing changed)");
        return Ok(0);
    }

    if !force
        && !crate::bootc::confirm(&format!(
            "Apply these changes to the live usr-overlay with {}?",
            backend.tool()
        ))
    {
        println!("  Skipped — run 'dcli-bootc overlay sync' when ready.");
        return Ok(0);
    }

    backend.install_packages(&to_install, false)?;
    backend.remove_packages(&to_remove, false)?;
    for (path, name) in &local_to_stage {
        backend.stage_local_rpm(path, name)?;
    }
    for (path, _) in &local_to_install {
        backend.install_local_rpm(path, false)?;
    }

    let mut extras = Vec::new();
    if !retained.is_empty() {
        extras.push(format!("{} base-provided kept", retained.len()));
    }
    if !kept.is_empty() {
        extras.push(format!("{} kept (not declared)", kept.len()));
    }
    if !local_to_install.is_empty() {
        extras.push(format!("{} local RPM(s) installed", local_to_install.len()));
    }
    if !local_to_stage.is_empty() {
        extras.push(format!("{} local RPM(s) restaged", local_to_stage.len()));
    }
    let suffix = if extras.is_empty() {
        String::new()
    } else {
        format!(", {}", extras.join(", "))
    };
    println!(
        "{} Overlay synced ({} installed, {} removed{})",
        "✓".green(),
        to_install.len(),
        to_remove.len(),
        suffix
    );
    Ok(to_install.len() + to_remove.len() + local_to_install.len() + local_to_stage.len())
}

/// Upgrade the packages already installed in the live host overlay, ignoring
/// the manifest (it refreshes whatever the overlay currently holds). Used by
/// `dcli-bootc update` and `overlay upgrade`. Prompts before running unless
/// `force`. No-op when the project has no `overlay_module` or no usable
/// backend. Returns the number of packages the backend was asked to upgrade.
pub fn upgrade(profile: &Profile, force: bool, announce: bool) -> Result<usize> {
    if profile.overlay_module.is_none() {
        return Ok(0);
    }
    let Some(backend) = overlay::select(profile.overlay_backend) else {
        return Ok(0);
    };
    let backend: &dyn OverlayBackend = &*backend;

    let installed = backend.installed_packages()?;
    if installed.is_empty() {
        if announce {
            println!(
                "  Overlay has no packages to upgrade (module '{}').",
                profile.overlay_module.as_deref().unwrap_or("?")
            );
        }
        return Ok(0);
    }

    if announce {
        println!(
            "{} Overlay packages to upgrade with '{} upgrade':",
            "▶".cyan(),
            backend.tool()
        );
        for p in &installed {
            println!("    {} {}", "↑".cyan(), p);
        }
    }

    if !force
        && !crate::bootc::confirm(&format!(
            "Upgrade these {} overlay package(s) with {}?",
            installed.len(),
            backend.tool()
        ))
    {
        println!("  Skipped — run 'dcli-bootc overlay upgrade' when ready.");
        return Ok(0);
    }

    backend.upgrade_packages()?;

    if announce {
        println!("{} Overlay packages upgraded.", "✓".green());
    }
    Ok(installed.len())
}

/// `dcli-bootc overlay sync` — the build/update hook, on demand.
pub fn sync_command(project_dir: &Path, force: bool, dry_run: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    require_overlay(&profile)?;
    sync(project_dir, &profile, force, dry_run, true, true)?;
    Ok(())
}

/// `dcli-bootc overlay upgrade` — upgrade the overlay's installed packages on
/// demand (the same step `dcli-bootc update` runs).
pub fn upgrade_command(project_dir: &Path, force: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    require_overlay(&profile)?;
    upgrade(&profile, force, true)?;
    Ok(())
}

/// `dcli-bootc overlay prune` — drop from the overlay module every package
/// the currently booted base image already provides.
///
/// Unlike `base_provided_packages`, this deliberately consults *only* the
/// booted base image's package list and never the `enabled_modules`
/// declarations: a package is pruned only once it is actually installed and
/// running, never merely declared for a build that hasn't booted yet.
pub fn prune(project_dir: &Path, dry_run: bool, force: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let (module_name, backend) = require_overlay(&profile)?;
    let backend: &dyn OverlayBackend = &*backend;

    let path = config::module_path(project_dir, module_name).unwrap_or_else(|| {
        project_dir
            .join("modules")
            .join(format!("{}.yaml", module_name))
    });
    let module = config::load_module(project_dir, module_name)?;

    let mut declared = module.packages;
    declared.sort();
    declared.dedup();

    let base = backend.base_packages().context(
        "Could not determine the base image's packages — refusing to prune without them",
    )?;
    let (to_prune, remaining) = prune_partition(&declared, &base);

    if to_prune.is_empty() {
        println!(
            "{} Nothing to prune — no package in '{}' is provided by the booted base image.",
            "✓".green(),
            module_name
        );
        return Ok(());
    }

    println!(
        "{} Pruning {} base-provided package(s) from {}",
        "▶".cyan(),
        to_prune.len(),
        path.display()
    );
    for p in &to_prune {
        println!("    {} {}", "-".yellow(), p);
    }
    println!("    {} left in the module", remaining.len());

    if dry_run {
        println!("  (dry run — nothing written)");
        return Ok(());
    }

    if !force
        && !crate::bootc::confirm("Remove these base-provided packages from the overlay module?")
    {
        println!("  Skipped.");
        return Ok(());
    }

    rewrite_module_packages(&path, &remaining, backend)?;

    println!(
        "{} Pruned {} package(s) from '{}'; {} left",
        "✓".green(),
        to_prune.len(),
        module_name,
        remaining.len()
    );
    if backend.supports_reset() {
        println!(
            "  {} Live overlay copies are left as-is (removing them with {} would hide the base image's copies). Reclaim them with 'rakuos reset-overlay --soft'.",
            "!".yellow(),
            backend.tool()
        );
    } else {
        println!(
            "  {} Live overlay copies are left as-is (removing them with {} would hide the base image's copies).",
            "!".yellow(),
            backend.tool()
        );
    }
    Ok(())
}

/// The overlay module's declared local RPM filenames.
fn manifest_local_rpms(project_dir: &Path, profile: &Profile) -> Vec<String> {
    let Some(module_name) = profile.overlay_module.as_deref() else {
        return Vec::new();
    };
    config::load_module(project_dir, module_name)
        .map(|m| m.local_rpms)
        .unwrap_or_default()
}

/// Declared overlay local RPMs resolved to (project path, package name).
fn declared_local_rpms(project_dir: &Path, profile: &Profile) -> Vec<(PathBuf, String)> {
    manifest_local_rpms(project_dir, profile)
        .into_iter()
        .filter_map(|entry| {
            let name = plan::local_rpm_package_name(project_dir, &entry)?;
            Some((project_dir.join("rpms").join(entry), name))
        })
        .collect()
}

/// True when a backend's staged copy of a local RPM is missing, blank, or a
/// different size than the project's file (e.g. after a soft reset blanked it).
/// Backends without local-RPM support are never "stale".
fn staged_needs_repair(backend: &dyn OverlayBackend, src: &Path, name: &str) -> bool {
    let Some(staged) = backend.staged_local_rpm(name) else {
        return false;
    };
    match (std::fs::metadata(src), std::fs::metadata(&staged)) {
        (Ok(s), Ok(d)) => d.len() == 0 || d.len() != s.len(),
        (_, Err(_)) => true,
        (Err(_), _) => false,
    }
}

/// Entries present in `have` but absent from `want`.
fn undeclared(have: &[String], want: &[String]) -> Vec<String> {
    have.iter()
        .filter(|p| !want.contains(p))
        .cloned()
        .collect()
}

/// `dcli-bootc overlay clean` — rewrite the live overlay's package lists so
/// they match the overlay module exactly, then (when the backend supports it)
/// offer to schedule the reset that rebuilds the overlay from them.
///
/// `sync` reconciles the overlay with the backend's installer, but a remover
/// must never erase a package the base image provides (it would whiteout the
/// base copy), and some resets preserve `packages.list` — so entries the base
/// now provides (or that were dropped from the module) otherwise linger in the
/// live overlay. This is the command that clears them from the record.
pub fn clean(
    project_dir: &Path,
    dry_run: bool,
    force: bool,
    no_reset: bool,
    host: Option<&str>,
) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let (module_name, backend) = require_overlay(&profile)?;
    let module_name = module_name.to_string();
    let backend: &dyn OverlayBackend = &*backend;

    let mut declared = manifest_packages(project_dir, &profile)?;
    if declared.is_empty() {
        anyhow::bail!(
            "overlay_module '{}' declares no packages — refusing to clean the live overlay. Run 'dcli-bootc overlay import' first.",
            module_name
        );
    }
    declared.sort();
    declared.dedup();

    let declared_local_entries = manifest_local_rpms(project_dir, &profile);
    let mut declared_local: Vec<String> = if backend.supports_local_rpms() {
        declared_local_entries
            .iter()
            .filter_map(|e| plan::local_rpm_package_name(project_dir, e))
            .collect()
    } else {
        Vec::new()
    };
    declared_local.sort();
    declared_local.dedup();

    let installed = backend.installed_packages()?;
    let installed_local = backend.installed_local_rpms();
    let base = base_provided_packages(project_dir, &profile, backend);

    let repo_drops = undeclared(&installed, &declared);
    let local_drops = undeclared(&installed_local, &declared_local);

    println!("{} {}", "▶".cyan(), backend.label());
    println!("  Manifest module: {}", module_name);
    println!("  packages.list:     {} -> {}", installed.len(), declared.len());
    println!(
        "  packages-rpm.list: {} -> {}",
        installed_local.len(),
        declared_local.len()
    );
    println!();

    if repo_drops.is_empty() && local_drops.is_empty() {
        println!(
            "{} Live lists already match the manifest — nothing to drop.",
            "✓".green()
        );
    }
    if !repo_drops.is_empty() {
        println!("  {} package(s) to drop from packages.list:", "-".yellow());
        for p in &repo_drops {
            if base.contains(p) {
                println!(
                    "    {} {} {}",
                    "=".cyan(),
                    p,
                    "(base image provides it)".dimmed()
                );
            } else {
                println!("    {} {}", "-".yellow(), p);
            }
        }
    }
    if !local_drops.is_empty() {
        println!(
            "  {} local RPM(s) to drop from packages-rpm.list:",
            "-".yellow()
        );
        for p in &local_drops {
            println!("    {} {}", "-".yellow(), p);
        }
    }
    if !repo_drops.is_empty() && backend.supports_reset() {
        println!();
        println!(
            "  {} Entries not marked \"(base image provides it)\" will be gone after the reset.",
            "!".yellow()
        );
    }

    // Declared local RPMs the reset would not be able to reinstall.
    for entry in &declared_local_entries {
        if plan::local_rpm_package_name(project_dir, entry).is_none() {
            println!(
                "  {} Could not read local RPM '{}' from the project's rpms/ directory.",
                "!".yellow(),
                entry
            );
        }
    }
    for name in &declared_local {
        let stored = backend.staged_local_rpm(name);
        let missing = stored.as_ref().map_or(true, |p| !p.exists());
        if missing {
            println!(
                "  {} No stored copy for local RPM '{}' — the reset cannot reinstall it.",
                "!".yellow(),
                name
            );
        }
    }

    if dry_run {
        println!("  (dry run — nothing written)");
        return Ok(());
    }

    let changed = !repo_drops.is_empty() || !local_drops.is_empty();
    if changed {
        if !force
            && !crate::bootc::confirm("Rewrite the live overlay lists and prepare a reset?")
        {
            println!("  Skipped.");
            return Ok(());
        }
        backend.write_package_lists(&declared, &declared_local)?;
        println!(
            "{} Wrote packages.list ({} entries) and packages-rpm.list ({} entries); originals saved as .bak",
            "✓".green(),
            declared.len(),
            declared_local.len()
        );
    } else {
        println!("{} Live lists already match the manifest.", "✓".green());
    }

    if no_reset {
        if backend.supports_reset() {
            println!();
            println!("  Next: run 'sudo rakuos reset-overlay --soft' and reboot to rebuild the overlay.");
        }
        return Ok(());
    }

    if !backend.supports_reset() {
        println!();
        println!(
            "  {} '{}' has no overlay reset — the rewritten lists take effect on the next overlay rebuild.",
            "!".yellow(),
            backend.tool()
        );
        return Ok(());
    }

    if force || crate::bootc::confirm("Run 'sudo rakuos reset-overlay --soft' now?") {
        backend.schedule_reset()?;
        println!(
            "{} Soft reset scheduled — reboot to rebuild the overlay.",
            "✓".green()
        );
        println!("  Run 'sudo reboot' when ready.");
    } else {
        println!();
        println!("  Skipped. Run 'sudo rakuos reset-overlay --soft' and reboot when ready.");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::overlay::RumBackend;

    fn profile_with_overlay(module: Option<&str>) -> Profile {
        Profile {
            name: "test".to_string(),
            base_image: "img".to_string(),
            nvidia_base_image: None,
            default_tag: "latest".to_string(),
            enabled_modules: Vec::new(),
            package_manager: config::PackageManager::default(),
            dotfiles: Vec::new(),
            overlay_module: module.map(str::to_string),
            overlay_backend: config::OverlayBackend::default(),
            kernel: None,
        }
    }

    #[test]
    fn upgrade_is_a_noop_without_an_overlay_module() {
        assert_eq!(upgrade(&profile_with_overlay(None), false, false).unwrap(), 0);
    }

    #[test]
    fn diff_is_bidirectional() {
        let installed = ["a", "b", "c"].map(String::from).to_vec();
        let manifest = ["b", "d"].map(String::from).to_vec();
        let (to_install, to_remove) = diff(&installed, &manifest);
        assert_eq!(to_install, ["d"]);
        assert_eq!(to_remove, ["a", "c"]);
    }

    #[test]
    fn prune_partition_separates_base_provided() {
        let declared = ["a", "b", "c"].map(String::from).to_vec();
        let base: HashSet<String> = ["b", "c", "d"].map(String::from).into_iter().collect();
        let (to_prune, remaining) = prune_partition(&declared, &base);
        assert_eq!(to_prune, ["b", "c"]);
        assert_eq!(remaining, ["a"]);
    }

    #[test]
    fn take_retained_pulls_base_provided_out_of_removals() {
        let base: HashSet<String> = ["foo".to_string()].into_iter().collect();
        let mut to_remove = vec!["foo".to_string(), "bar".to_string()];
        let retained = take_retained(&mut to_remove, &base);
        assert_eq!(to_remove, ["bar"]);
        assert_eq!(retained, ["foo"]);
    }

    #[test]
    fn write_module_merges_and_preserves_other_keys() {
        let dir = std::env::temp_dir().join(format!("dcli-overlay-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("overlay.yaml");
        std::fs::write(&path, "description: keep me\nscripts:\n  post: echo hi\n").unwrap();

        write_module(&path, &["steam".to_string()], false, &RumBackend).unwrap();

        let out = std::fs::read_to_string(&path).unwrap();
        assert!(out.contains("keep me"), "{out}");
        assert!(out.contains("echo hi"), "{out}");
        assert!(out.contains("- steam"), "{out}");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn removed_packages_reads_enabled_module_removals() {
        let dir = std::env::temp_dir().join(format!("dcli-removals-test-{}", std::process::id()));
        let modules = dir.join("modules");
        std::fs::create_dir_all(&modules).unwrap();
        std::fs::write(
            modules.join("removals.yaml"),
            "description: test\nremove:\n  - fcitx5\n  - hid-fanatecff\n",
        )
        .unwrap();
        let mut profile = profile_with_overlay(None);
        profile.enabled_modules = vec!["removals".to_string()];

        let removed = removed_packages(&dir, &profile);
        assert!(removed.contains("fcitx5"));
        assert!(removed.contains("hid-fanatecff"));
        assert_eq!(removed.len(), 2);
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn undeclared_finds_entries_missing_from_want() {
        let have = ["a", "b", "c"].map(String::from).to_vec();
        let want = ["b", "d"].map(String::from).to_vec();
        assert_eq!(undeclared(&have, &want), ["a", "c"]);
        assert_eq!(undeclared(&want, &have), ["d"]);
    }
}
