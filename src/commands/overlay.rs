//! `dcli-bootc overlay` — RakuOS/rum usr-overlay integration.

use anyhow::{Context, Result};
use colored::*;
use std::path::Path;

use crate::config::{self, Profile};
use crate::overlay;

/// The overlay module's declared packages — the declarative manifest of what
/// should be installed in the live RakuOS usr-overlay. Not part of the image
/// build (overlay packages stay in the overlay, managed by rum).
fn manifest_packages(project_dir: &Path, profile: &Profile) -> Result<Vec<String>> {
    let Some(module_name) = profile.overlay_module.as_deref() else {
        return Ok(Vec::new());
    };
    let mut pkgs = match config::load_module(project_dir, module_name) {
        Ok(m) => m.packages,
        Err(_) => Vec::new(),
    };
    pkgs.sort();
    pkgs.dedup();
    Ok(pkgs)
}

/// (to_install, to_remove) to make the host overlay match the manifest.
fn diff(installed: &[String], manifest: &[String]) -> (Vec<String>, Vec<String>) {
    let to_install = manifest
        .iter()
        .filter(|p| !installed.contains(p))
        .cloned()
        .collect();
    let to_remove = installed
        .iter()
        .filter(|p| !manifest.contains(p))
        .cloned()
        .collect();
    (to_install, to_remove)
}

fn require_overlay(profile: &Profile) -> Result<&str> {
    let module = profile
        .overlay_module
        .as_deref()
        .context("This project has no 'overlay_module' set in profile.yaml (e.g. 'overlay_module: overlay')")?;
    if !overlay::available() {
        anyhow::bail!(
            "RakuOS rum overlay not found on this host (need /var/lib/rakuos/packages.list and 'rum' in PATH)"
        );
    }
    Ok(module)
}

/// `overlay import`: snapshot the host overlay's packages into the module.
pub fn import(project_dir: &Path, dry_run: bool, force: bool) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, None)?;
    let module_name = require_overlay(&profile)?;

    let installed = overlay::installed_packages()?;
    let path = config::module_path(project_dir, module_name)
        .unwrap_or_else(|| project_dir.join("modules").join(format!("{}.yaml", module_name)));

    println!(
        "{} Importing {} overlay package(s) into {}",
        "▶".cyan(),
        installed.len(),
        path.display()
    );

    if installed.is_empty() {
        println!("  {}", "Overlay has no packages — nothing to write.".dimmed());
        return Ok(());
    }

    if dry_run {
        println!("  Would write packages:");
        for p in &installed {
            println!("    {}", p);
        }
        return Ok(());
    }

    write_module(&path, &installed, force)?;

    println!("{} Wrote {} package(s)", "✓".green(), installed.len());
    if profile.enabled_modules.iter().any(|m| m == module_name) {
        println!(
            "  {} module '{}' is in enabled_modules — its packages will ALSO be baked into the image. Remove it from enabled_modules to keep them overlay-only.",
            "!".yellow(),
            module_name
        );
    }
    let local = overlay::installed_local_rpms();
    if !local.is_empty() {
        println!(
            "  {} Locally-installed overlay RPMs are not imported (no repo provides them) — declare them as local_rpms/remote_rpms: {}",
            "!".yellow(),
            local.join(", ")
        );
    }
    println!(
        "  Next: run 'dcli-bootc overlay sync' (or build/update) to install/remove overlay packages with rum."
    );
    Ok(())
}

/// Write the overlay packages into the module, preserving any other keys
/// already in the file (scripts, repos, ...).
fn write_module(path: &Path, packages: &[String], force: bool) -> Result<()> {
    const HEADER: &str = "# Generated by 'dcli-bootc overlay import' from the RakuOS usr-overlay.";

    let mut map: serde_yaml::Mapping = if path.exists() {
        let existing = std::fs::read_to_string(path)
            .with_context(|| format!("Failed to read {}", path.display()))?;

        if !force && !existing.contains(HEADER) {
            let has_packages = serde_yaml::from_str::<serde_yaml::Value>(&existing)
                .ok()
                .and_then(|v| v.get("packages").and_then(|p| p.as_sequence().map(|s| !s.is_empty())))
                .unwrap_or(false);
            if has_packages {
                anyhow::bail!(
                    "{} already declares packages and was not created by dcli-bootc — re-run with --force to overwrite them",
                    path.display()
                );
            }
        }

        match serde_yaml::from_str::<serde_yaml::Value>(&existing)? {
            serde_yaml::Value::Mapping(m) => m,
            _ => anyhow::bail!("{} is not a YAML mapping", path.display()),
        }
    } else {
        serde_yaml::Mapping::new()
    };

    if !map.contains_key("description") {
        map.insert(
            "description".into(),
            "RakuOS usr-overlay packages (imported from rum)".into(),
        );
    }
    map.insert(
        "packages".into(),
        serde_yaml::Value::Sequence(
            packages
                .iter()
                .map(|p| serde_yaml::Value::String(p.clone()))
                .collect(),
        ),
    );

    let yaml = serde_yaml::to_string(&serde_yaml::Value::Mapping(map))?;
    let body = format!(
        "{}\n# Packages removed from this list are uninstalled with 'rum remove' on the next build/update.\n{}",
        HEADER, yaml
    );
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    Ok(())
}

/// `overlay status`: show drift between the host overlay and the manifest.
pub fn status(project_dir: &Path, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    let module_name = require_overlay(&profile)?;

    let manifest = manifest_packages(project_dir, &profile)?;
    let installed = overlay::installed_packages()?;
    let (to_install, to_remove) = diff(&installed, &manifest);

    println!("{} RakuOS overlay (rum)", "▶".cyan());
    println!("  Manifest module: {}", module_name);
    println!("  Overlay packages installed: {}", installed.len());
    println!("  Packages declared in manifest: {}", manifest.len());
    println!();

    let both: Vec<&String> = installed.iter().filter(|p| manifest.contains(p)).collect();
    if !both.is_empty() {
        println!("  {} in overlay and manifest ({}):", "✓".green(), both.len());
        for p in both {
            println!("    {}", p);
        }
    }
    if !to_install.is_empty() {
        println!(
            "  {} declared but not installed ({}):",
            "+".cyan(),
            to_install.len()
        );
        for p in &to_install {
            println!("    {}", p);
        }
    }
    if !to_remove.is_empty() {
        println!(
            "  {} installed but not declared ({}):",
            "-".yellow(),
            to_remove.len()
        );
        for p in &to_remove {
            println!("    {}", p);
        }
    }

    println!();
    if to_install.is_empty() && to_remove.is_empty() {
        println!("{} Overlay matches the manifest.", "✓".green());
    } else {
        println!(
            "{} Run 'dcli-bootc overlay sync' (or build/update) to {} and {} with rum.",
            "➜".yellow(),
            format!("install {}", to_install.len()),
            format!("remove {}", to_remove.len())
        );
    }

    let local = overlay::installed_local_rpms();
    if !local.is_empty() {
        println!();
        println!(
            "  Locally-installed overlay RPMs (declare as local_rpms/remote_rpms): {}",
            local.join(", ")
        );
    }
    Ok(())
}

/// Reconcile the live host overlay with the manifest module: `rum install`
/// packages the manifest adds, `rum remove` packages it drops. Used by
/// build/update and `overlay sync`. Returns the number of packages changed.
pub fn sync(
    project_dir: &Path,
    profile: &Profile,
    force: bool,
    dry_run: bool,
    announce: bool,
) -> Result<usize> {
    if profile.overlay_module.is_none() || !overlay::available() {
        return Ok(0);
    }

    let manifest = manifest_packages(project_dir, profile)?;
    if manifest.is_empty() {
        // Safety: an empty/missing manifest must never wipe the live overlay.
        if announce {
            println!(
                "{} overlay_module '{}' declares no packages — run 'dcli-bootc overlay import' first; nothing to sync.",
                "!".yellow(),
                profile.overlay_module.as_deref().unwrap_or("?")
            );
        }
        return Ok(0);
    }

    let installed = overlay::installed_packages()?;
    let (to_install, to_remove) = diff(&installed, &manifest);
    if to_install.is_empty() && to_remove.is_empty() {
        if announce {
            println!("{} Overlay matches the manifest.", "✓".green());
        }
        return Ok(0);
    }

    println!();
    println!(
        "{} RakuOS overlay sync with '{}':",
        "▶".cyan(),
        profile.overlay_module.as_deref().unwrap_or("?")
    );
    for p in &to_install {
        println!("    {} install {}", "+".green(), p);
    }
    for p in &to_remove {
        println!("    {} remove  {}", "-".yellow(), p);
    }

    if dry_run {
        println!("  (dry run — nothing changed)");
        return Ok(0);
    }

    if !force && !crate::bootc::confirm("Apply these changes to the live usr-overlay with rum?") {
        println!("  Skipped — run 'dcli-bootc overlay sync' when ready.");
        return Ok(0);
    }

    overlay::install_packages(&to_install, false)?;
    overlay::remove_packages(&to_remove, false)?;

    println!(
        "{} Overlay synced ({} installed, {} removed)",
        "✓".green(),
        to_install.len(),
        to_remove.len()
    );
    Ok(to_install.len() + to_remove.len())
}

/// `dcli-bootc overlay sync` — the build/update hook, on demand.
pub fn sync_command(project_dir: &Path, force: bool, dry_run: bool, host: Option<&str>) -> Result<()> {
    let (profile, _) = config::resolve_effective_profile(project_dir, host)?;
    require_overlay(&profile)?;
    sync(project_dir, &profile, force, dry_run, true)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn diff_is_bidirectional() {
        let installed = ["a", "b", "c"].map(String::from).to_vec();
        let manifest = ["b", "d"].map(String::from).to_vec();
        let (to_install, to_remove) = diff(&installed, &manifest);
        assert_eq!(to_install, ["d"]);
        assert_eq!(to_remove, ["a", "c"]);
    }

    #[test]
    fn write_module_merges_and_preserves_other_keys() {
        let dir = std::env::temp_dir().join(format!("dcli-overlay-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("overlay.yaml");
        std::fs::write(&path, "description: keep me\nscripts:\n  post: echo hi\n").unwrap();

        write_module(&path, &["steam".to_string()], false).unwrap();

        let out = std::fs::read_to_string(&path).unwrap();
        assert!(out.contains("keep me"), "{out}");
        assert!(out.contains("echo hi"), "{out}");
        assert!(out.contains("- steam"), "{out}");
        std::fs::remove_dir_all(&dir).ok();
    }
}
