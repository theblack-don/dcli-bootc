use anyhow::Result;
use std::path::Path;

use crate::config::Profile;
use crate::module::{load_enabled_modules, ResolvedModule};

/// Generated output files
pub struct GeneratedFiles {
    pub containerfile: String,
    pub build_sh: String,
}

/// Generate Containerfile and build.sh from a profile + its modules
pub fn generate(project_dir: &Path, profile: &Profile) -> Result<GeneratedFiles> {
    let modules = load_enabled_modules(project_dir, &profile.enabled_modules)?;

    let containerfile = generate_containerfile(profile);
    let build_sh = generate_build_sh(profile, &modules);

    Ok(GeneratedFiles {
        containerfile,
        build_sh,
    })
}

fn generate_containerfile(profile: &Profile) -> String {
    format!(
        r#"ARG BASE_IMAGE={0}

FROM scratch AS ctx
COPY build_files /
COPY files /files

FROM ${{BASE_IMAGE}}

RUN --mount=type=bind,from=ctx,source=/,target=/ctx \
    --mount=type=cache,dst=/var/cache \
    --mount=type=tmpfs,dst=/tmp \
    /ctx/build.sh

RUN bootc container lint
"#,
        profile.base_image
    )
}

fn generate_build_sh(profile: &Profile, modules: &[ResolvedModule]) -> String {
    let mut lines = Vec::new();

    lines.push("#!/usr/bin/env bash".to_string());
    lines.push("set -euo pipefail".to_string());
    lines.push(String::new());
    lines.push(format!("# Generated by dcli-bootc gen — edit modules/*.yaml instead"));
    lines.push(format!("# Profile: {}", profile.name));
    lines.push(String::new());

    for rm in modules {
        let m = &rm.module;

        // Skip empty modules with only a note
        let has_repos = !m.repos.copr.is_empty()
            || !m.repos.rpm_urls.is_empty()
            || !m.repos.enable.is_empty()
            || !m.repos.import_keys.is_empty();
        let has_remove = !m.remove.is_empty();
        let has_install = !m.packages.is_empty() || !m.remote_rpms.is_empty();
        let has_files = !m.files.is_empty();
        let has_scripts = m.scripts.pre.is_some() || m.scripts.post.is_some();
        let has_services = !m.services.is_empty() || !m.first_boot_services.is_empty();

        if !has_repos && !has_remove && !has_install && !has_files && !has_scripts && !has_services {
            continue;
        }

        lines.push(String::new());
        lines.push(format!("# === {}: {} ===", rm.name, m.description));

        // ── Pre script ──
        if let Some(script) = &m.scripts.pre {
            lines.push(String::new());
            lines.push(format!("# pre script ({})", rm.name));
            for line in script.trim().lines() {
                lines.push(line.to_string());
            }
        }

        // ── Repos ──
        if !m.repos.import_keys.is_empty() {
            for key in &m.repos.import_keys {
                lines.push(format!("rpmkeys --import \"{}\"", key));
            }
        }

        for copr in &m.repos.copr {
            lines.push(format!("dnf5 -y copr enable {}", copr));
        }

        for repo in &m.repos.rpm_urls {
            let name = &repo.name;
            let baseurl = &repo.baseurl;
            lines.push(format!(
                r#"cat > /etc/yum.repos.d/{}.repo << 'REPO'
[{}]
name={}
baseurl={}
type=rpm-md
skip_if_unavailable=True
gpgcheck={}
repo_gpgcheck=0
enabled=1
enabled_metadata=1
REPO"#,
                name,
                name,
                name,
                baseurl,
                if repo.gpgkey.is_some() { "1" } else { "0" },
            ));
            if let Some(gpgkey) = &repo.gpgkey {
                lines.push(format!("rpmkeys --import \"{}\"", gpgkey));
            }
        }

        for repo_name in &m.repos.enable {
            lines.push(format!(
                r#"sed -i 's/enabled=0/enabled=1/' /etc/yum.repos.d/{}.repo"#,
                repo_name
            ));
        }

        // ── Remove packages ──
        if !m.remove.is_empty() {
            let pkgs = m.remove.join(" \\\n    ");
            lines.push(String::new());
            lines.push(format!("dnf remove -y \\\n    {}", pkgs));
        }

        // ── Install packages ──
        if !m.packages.is_empty() {
            let pkgs = m.packages.join(" \\\n    ");
            lines.push(String::new());
            lines.push(format!("dnf install -y --skip-unavailable \\\n    {}", pkgs));
        }

        // ── Remote RPMs ──
        for rpm in &m.remote_rpms {
            let filename = rpm
                .filename
                .clone()
                .unwrap_or_else(|| {
                    rpm.url
                        .rsplit('/')
                        .next()
                        .unwrap_or("package.rpm")
                        .to_string()
                });
            let sha_part = if let Some(_sha) = &rpm.sha256 {
                // Could add sha256sum verification
                String::new()
            } else {
                String::new()
            };
            lines.push(format!(
                "curl -L -o /tmp/{} \"{}\"{}",
                filename,
                rpm.url,
                if sha_part.is_empty() { "" } else { " && \\" }
            ));
            if !sha_part.is_empty() {
                // Re-emit the install on the next line
            }
        }

        if !m.remote_rpms.is_empty() {
            let rpm_files: Vec<String> = m
                .remote_rpms
                .iter()
                .map(|r| {
                    r.filename
                        .clone()
                        .unwrap_or_else(|| {
                            r.url.rsplit('/').next().unwrap_or("package.rpm").to_string()
                        })
                })
                .map(|f| format!("/tmp/{}", f))
                .collect();
            lines.push(format!("dnf install -y \\\n    {}", rpm_files.join(" \\\n    ")));
            lines.push("rm -f /tmp/*.rpm".to_string());
        }

        // ── Files overlay ──
        if !m.files.is_empty() {
            lines.push(String::new());
            lines.push("# Copy files/ tree into image".to_string());
            lines.push("rsync -rlptD /ctx/files/ /".to_string());
        }

        // ── Post script ──
        if let Some(script) = &m.scripts.post {
            lines.push(String::new());
            lines.push(format!("# post script ({})", rm.name));
            for line in script.trim().lines() {
                lines.push(line.to_string());
            }
        }

        // ── Services (always-on) ──
        for svc in &m.services {
            lines.push(format!("systemctl enable {}", svc));
        }

        // ── First-boot services (ConditionPathExists guard) ──
        for fb_svc in &m.first_boot_services {
            let unit_name = &fb_svc.name;
            let unit_path = format!("/etc/systemd/system/{}", unit_name);
            let cond_path = &fb_svc.condition_path;

            if let Some(content) = &fb_svc.unit_content {
                lines.push(format!(
                    r#"install -Dm0644 /dev/stdin {} << 'SVC'
{}"#,
                    unit_path, content
                ));
                lines.push("SVC".to_string());
            } else {
                lines.push(format!(
                    "# First-boot service: {} (guarded by ConditionPathExists={})",
                    unit_name, cond_path
                ));
            }
            lines.push(format!("systemctl enable {}", unit_name));
        }
    }

    // ── Final cleanup ──
    lines.push(String::new());
    lines.push("# === cleanup ===".to_string());
    lines.push("dnf clean all && rm -rf /var/cache/dnf/*".to_string());
    lines.push(String::new());

    lines.join("\n")
}

/// Preview the generated output without writing
pub fn preview(project_dir: &Path, profile: &Profile) -> Result<GeneratedFiles> {
    generate(project_dir, profile)
}
